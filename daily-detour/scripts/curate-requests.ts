/**
 * Neighbours' special deliveries (authoring tool). Picks three puzzles per
 * neighbour from a generator pool (two medium, one hard, from the neighbour's
 * own kind of town), names them, and writes src/data/requests.ts.
 *
 *   npx vite-node scripts/curate-requests.ts <pool-dir>
 *
 * The pool is plain generator output, e.g.
 *   npx vite-node scripts/generate.ts ring medium 9100 5 <pool-dir>/ring-medium.jsonl mix
 */
declare const process: { argv: string[] };
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { encodePuzzle } from '../src/data/codec';
import { GENERATED_PACKS } from '../src/data/generated';
import { brief, hint, usedTitles } from './curate';
import type { Candidate, Family } from './generate';

const dir = process.argv[2];
const WHO: { id: string; family: Family; titles: [string, string, string] }[] = [
  { id: 'mabel', family: 'ring', titles: ['Mabel’s Honey Round', 'Swarm Season', 'The Queen’s Garden Party'] },
  { id: 'bram', family: 'grid', titles: ['Every Clock in Town', 'Half Past the Hour', 'The Town Hall Chimes'] },
  { id: 'ivy', family: 'tri', titles: ['Second Post', 'Parcels for the Lanes', 'Return to Sender'] },
  { id: 'felix', family: 'river', titles: ['Wet Paint', 'Both Banks at Dawn', 'The Riverside Exhibition'] },
];

for (const p of GENERATED_PACKS) for (const c of p.codes) usedTitles.add(c.split('|')[0]);
const pool: Candidate[] = [];
for (const f of readdirSync(dir).filter((x) => x.endsWith('.jsonl'))) {
  for (const line of readFileSync(`${dir}/${f}`, 'utf8').split('\n')) if (line.trim()) pool.push(JSON.parse(line));
}
const best = (family: Family, band: string, n: number) =>
  pool.filter((c) => c.family === family && c.band === band).sort((a, b) => b.score - a.score).slice(0, n);

const out: Record<string, string[]> = {};
for (const w of WHO) {
  const chosen = [...best(w.family, 'medium', 2), ...best(w.family, 'hard', 1)].sort((a, b) => a.difficulty - b.difficulty);
  if (chosen.length !== 3) throw new Error(`${w.id}: only ${chosen.length} puzzles`);
  out[w.id] = chosen.map((c, i) => encodePuzzle({ ...c.def, title: w.titles[i], brief: brief(c), hint: hint(c) }));
}

const body = `// Generated by scripts/curate-requests.ts from solver-checked generator output. Do not edit by hand.
// Special deliveries for the neighbours who move into the village: three each, gentle to tricky.

export const REQUEST_CODES: Record<string, string[]> = ${JSON.stringify(out, null, 1)};
`;
writeFileSync('src/data/requests.ts', body);
for (const [id, codes] of Object.entries(out)) console.log(id, codes.map((c) => `${c.split('|')[0]} (gold ${c.split('|')[3]})`).join(' · '));
